def fecha_larga(fecha, idioma: str) -> str:
    """La fecha escrita como se hace en cada idioma, por ejemplo
    «Miércoles, 11 de noviembre de 2026» o «Wednesday, 11 November 2026»."""
    dia_semana = DIAS[idioma][fecha.weekday()]
    if idioma == "zh":
        return f"{fecha.year}年{fecha.month}月{fecha.day}日 {dia_semana}"
    mes = MESES[idioma][fecha.month - 1]
    if idioma == "es":
        texto = f"{dia_semana}, {fecha.day} de {mes} de {fecha.year}"
    elif idioma == "pt":
        texto = f"{dia_semana}, {fecha.day} de {mes} de {fecha.year}"
    elif idioma == "de":
        texto = f"{dia_semana}, {fecha.day}. {mes} {fecha.year}"
    elif idioma == "fr":
        texto = f"{dia_semana} {'1er' if fecha.day == 1 else fecha.day} {mes} {fecha.year}"
    elif idioma == "ru":
        texto = f"{dia_semana}, {fecha.day} {mes} {fecha.year} г."
    else:                                   # inglés
        texto = f"{dia_semana}, {fecha.day} {mes} {fecha.year}"
    return texto[0].upper() + texto[1:]


